B=input("Enter band colour: ")
C=B.lower()
if C=="black":
    print("0")
elif C=="brown":
    print("1")
elif C=="red":
    print("2")
elif C=="orange":
    print("3")
elif C=="yellow":
    print("4")
elif C=="green":
    print("5")
elif C=="blue":
    print("6")
elif C=="violet":
    print("7")
elif C=="grey":
    print("8")
elif C=="white":
    print("9")
else:
    print("Invalid input.")